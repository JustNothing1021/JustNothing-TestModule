on_install() {
  ui_print "- 正在释放文件"
  unzip -o "$ZIPFILE" 'system/*' -d $MODPATH >&2
  unzip -o "$ZIPFILE" 'common/*' -d $MODPATH >&2

  ui_print "- 检测设备架构: $ARCH"
  
  ui_print "- 安装Busybox..."
  magisk --install-module "$MODPATH/common/busybox.zip"
}

